"""Summarise the exact MINLP re-run (SCIP 10) for the report and the deck.

Reads  运行目录/results/windows_rerun/minlp/minlp_<inst>_t<T>.json  (written by 运行目录/rerun/minlp_scip.py),
re-checks every stored layout with the independent evaluator, and writes
  report/minlp_numbers.tex        (\newcommand macros used in the report)
  slides/pptx/minlp_summary.json  (strings used by slides/pptx/build_deck.js)
"""
import json
import sys
from pathlib import Path

V = Path(__file__).resolve().parents[1]
RUN = V.parents[2] / "项目" / "our-method" / "运行目录"
RES = RUN / "results" / "windows_rerun" / "minlp"
sys.path.insert(0, str(RUN))
from flp import evaluate, instance  # noqa: E402

INST = ["O7", "vC10a", "AB20", "SC30", "Du62"]
REF = {"O7": 131.6531381, "vC10a": 18522.79, "AB20": 5021.17, "SC30": 3343.47, "Du62": 3635307.30}
MAC = {"O7": "Oseven", "vC10a": "vCtena", "AB20": "ABtwenty", "SC30": "SCthirty", "Du62": "Dusixtytwo"}


def load(name, t):
    f = RES / f"minlp_{name}_t{t}.json"
    return json.loads(f.read_text()) if f.exists() else None


def fmt(v, d=2):
    return f"{v:,.{d}f}"


runs = {n: load(n, 300) for n in INST}
long = load("O7", 3600)

# independent re-check of every stored layout
for n, r in runs.items():
    if r and r["rects"]:
        ev = evaluate.evaluate(instance.load(n), r["rects"])
        assert ev["feasible"] and abs(ev["cost"] - r["cost"]) < 1e-9 * max(1, r["cost"]), (n, ev)
        r["gap_ref"] = 100 * (r["cost"] - REF[n]) / REF[n]
        opt = REF["O7"] if n == "O7" else None
        if opt:  # first time the incumbent was within 1e-6 relative of the optimum
            r["t_opt"] = next(t for t, v, _ in r["trace"] if v <= opt * (1 + 1e-6))
if long and long["rects"]:
    ev = evaluate.evaluate(instance.load("O7"), long["rects"])
    assert ev["feasible"]

# ---------------------------------------------------------------- report macros
M = []
def mac(k, v):
    M.append(f"\\newcommand{{\\{k}}}{{{v}}}")

for n in INST:
    r, k = runs[n], MAC[n]
    mac(f"mlStatus{k}", "time limit" if r["status"] == "timelimit" else r["status"])
    mac(f"mlTime{k}", f"{r['solving_time_s']:.0f}")
    mac(f"mlNodes{k}", f"{r['nodes']:,}".replace(",", "{,}"))
    mac(f"mlDual{k}", fmt(r["dual_bound"]).replace(",", "{,}"))
    mac(f"mlVars{k}", f"{r['n_vars']:,}".replace(",", "{,}"))
    mac(f"mlBin{k}", f"{r['n_bin']:,}".replace(",", "{,}"))
    if r["rects"]:
        mac(f"mlCost{k}", fmt(r["cost"]).replace(",", "{,}"))
        mac(f"mlGapRef{k}", f"{r['gap_ref']:.3f}" if n == "O7" else f"{r['gap_ref']:.2f}")
        mac(f"mlGap{k}", f"{r['gap_pct']:.1f}")
        mac(f"mlFirst{k}", f"{r['first_sol_time_s']:.0f}")
    else:
        mac(f"mlCost{k}", "none")
        mac(f"mlGapRef{k}", "0/1")
        mac(f"mlGap{k}", "--")
        mac(f"mlFirst{k}", "--")
o7 = runs["O7"]
mac("mlOsevenCostFull", f"{o7['cost']:.8f}")
mac("mlOsevenTopt", f"{o7['t_opt']:.0f}")
if long:
    mac("mlLongStatus", "optimal" if long["status"] == "optimal" else long["status"])
    mac("mlLongTime", f"{long['solving_time_s']:.0f}")
    mac("mlLongDual", f"{long['dual_bound']:.8f}")
    mac("mlLongCost", f"{long['cost']:.8f}")
    mac("mlLongGap", f"{long['gap_pct']:.2g}")
    mac("mlLongNodes", f"{long['nodes']:,}".replace(",", "{,}"))
(V / "report" / "minlp_numbers.tex").write_text(
    "% generated by scripts/summarize_minlp.py -- do not edit\n" + "\n".join(M) + "\n", encoding="utf8")

# ---------------------------------------------------------------- report subsection (generated)
def tx(v, d=2):
    return f"{v:,.{d}f}".replace(",", "{,}")


rows = []
for n in INST:
    r = runs[n]
    if r["rects"]:
        g = f"{r['gap_ref']:.3f}" if n == "O7" else f"{r['gap_ref']:.2f}"
        rows.append(f"{n} & {tx(r['cost'], 4 if n == 'O7' else 2)} & {g} & {tx(r['dual_bound'])} & "
                    f"{r['gap_pct']:.1f} & {tx(r['nodes'], 0)} & {r['first_sol_time_s']:.0f} & {r['solving_time_s']:.0f} \\\\")
    else:
        rows.append(f"{n} & none & -- & {tx(r['dual_bound'])} & -- & {tx(r['nodes'], 0)} & -- & {r['solving_time_s']:.0f} \\\\")
vc, du = runs["vC10a"], runs["Du62"]
if long and long["status"] == "optimal":
    rel = abs(long["cost"] - REF["O7"]) / REF["O7"]
    m, e = f"{rel:.0e}".split("e")
    long_txt = (f"The separate 3600\\,s run on O7 proves optimality: SCIP closes the gap after {tx(long['solving_time_s'], 0)}\\,s and "
                f"{tx(long['nodes'], 0)} nodes, with optimal value {long['cost']:.7f}. This equals the MINLPLib optimum "
                f"{REF['O7']:.7f} up to the feasibility tolerance (relative difference ${m}\\cdot10^{{{int(e)}}}$). Proving "
                f"optimality for seven departments thus takes this model about {long['solving_time_s'] / 60:.0f} minutes, while "
                f"every heuristic run on O7 takes 20\\,s.")
elif long:
    long_txt = (f"The separate 3600\\,s run on O7 does not prove optimality either: at the limit the dual bound is "
                f"{long['dual_bound']:.2f} (gap {long['gap_pct']:.1f}\\pct{{}}).")
else:
    long_txt = "The separate 3600\\,s run on O7 had not finished when this report was compiled."
sec = rf"""% generated by scripts/summarize_minlp.py -- do not edit
\subsection{{Exact MINLP reference}}
\label{{sec:res-minlp}}

\Cref{{tab:minlp}} gives the result of the exact MINLP (\cref{{sec:setup-methods}}), one 300\,s run per instance. It
finds a feasible layout only on the two smallest instances. On O7 its first layout appears after
{o7['first_sol_time_s']:.0f}\,s and the optimum {o7['cost']:.7f} after {o7['t_opt']:.0f}\,s, but at the time limit the dual
bound is still {tx(o7['dual_bound'])} (gap {o7['gap_pct']:.1f}\pct{{}}), so optimality is not proven. On vC10a the best
layout is {vc['gap_ref']:.2f}\pct{{}} above the reference, worse than every heuristic except the construction heuristic
(\cref{{tab:main}}). On AB20, SC30 and Du62 it finds no feasible layout; on Du62 SCIP does not get past the root node and
stops only after {du['solving_time_s']:.0f}\,s, beyond the limit. {long_txt} The pattern matches the unverified draft results
that this re-run replaces (optimum of O7 found but not proven within 300\,s, no feasible layout on AB20 and Du62), except
that the draft reported a poor feasible layout on SC30 (10{{,}}073.72), where this run finds none.

\begin{{table}}[htbp]
\centering
\caption[Exact MINLP reference]{{Exact convex MINLP, SCIP~10.0, one thread, one 300\,s run per instance (batch-B machine).
Gap ref.: $100\,(C-\text{{ref}})/\text{{ref}}$ with the references of \cref{{tab:main}}. Gap: SCIP's relative primal--dual gap at
the limit. Nodes: branch-and-bound nodes. First: time of the first feasible layout. Time: solver time at the stop. Both layouts
were re-checked by the independent evaluator.}}
\label{{tab:minlp}}
\small
\begin{{tabular}}{{lrrrrrrr}}
\toprule
Instance & Best layout & Gap ref.\ (\%) & Dual bound & Gap (\%) & Nodes & First (s) & Time (s)\\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
(V / "report" / "sections" / "05b_minlp.tex").write_text(sec, encoding="utf8")

# ---------------------------------------------------------------- deck strings
nofeas = [n for n in INST if not runs[n]["rects"]]
nf = ", ".join(nofeas)
du = runs["Du62"]
if long and long["status"] == "optimal":
    proof = (f"**O7, 3600 s run:** SCIP proved optimality after **{long['solving_time_s']:,.0f} s** "
             f"({long['nodes']:,} nodes); value {long['cost']:.7f}, equal to the MINLPLib optimum {REF['O7']:.7f} "
             f"up to the 10^{{−7}} feasibility tolerance ✓")
elif long:
    proof = (f"**O7, 3600 s run:** optimum {long['cost']:.7f} found, not proven; "
             f"dual bound {long['dual_bound']:.2f} (gap {long['gap_pct']:.1f}%)")
else:
    proof = "**O7, 3600 s run:** still running"
tab = [["Inst.", "Incumbent", "Gap ref. (%)", "Dual bound", "Nodes", "1st feasible"]]
for n in INST:
    r = runs[n]
    if r["rects"]:
        tab.append([n, fmt(r["cost"], 4 if n == "O7" else 2),f"{r['gap_ref']:.3f}" if n == "O7" else f"{r['gap_ref']:.2f}", fmt(r["dual_bound"]),
                    f"{r['nodes']:,}", f"{r['first_sol_time_s']:.0f} s"])
    else:
        tab.append([n, "none", "–", fmt(r["dual_bound"]), f"{r['nodes']:,}", "–"])
row = []
for n in INST:
    r = runs[n]
    row.append(("0.000" if n == "O7" else f"{r['gap_ref']:.2f}") if r["rects"] else "0/1")
S = {
    "f1": f"our MINLP, 300 s: O7 optimum found but not proven; no feasible layout on {nf}",
    "row": row,
    "footnote": f"MINLP: exact convex model, SCIP 10, one 300 s run per instance (batch B machine); 0/1 = no feasible layout. "
                f"Du62 stopped in the root node after {du['solving_time_s']:.0f} s.",
    "keybullet": f"Exact MINLP (300 s): finds the O7 optimum at {o7['t_opt']:.0f} s but cannot prove it; no feasible layout on {nf}",
    "auditline": "↻ MINLP code and logs lost → re-implemented and re-run (SCIP 10)",
    "auditfinding": "Code and logs not found",
    "auditaction": "Re-implemented from the documented model; re-run on batch B; new numbers used",
    "threat": "MINLP re-implemented from its documented description; one 300 s run per instance on the batch B machine; "
              "a stronger formulation or more time may do better (O7 needs a long run to prove optimality).",
    "nlayouts": "538",
    "batchnote": "MINLP (exact model): batch B machine, 6 solver runs at the same time, one thread each.",
    "modeltext": "Continuous positions and sizes; convex area constraint; four binaries per pair with big-M (M = W in x, H in y); "
                 "absolute-value distances. No symmetry breaking, no warm start; feasibility tolerance 10^{−7}. "
                 f"Du62: {du['n_vars']:,} variables, {du['n_bin']:,} binaries.",
    "table": tab,
    "proof": proof,
    "source": "Re-implementation of the model documented in the earlier draft (original code and logs lost). Batch B machine, "
              "6 runs at once, one thread each. Both stored layouts re-checked by the independent evaluator. "
              "Files: 运行目录/results/windows_rerun/minlp/.",
}
(V / "slides" / "pptx" / "minlp_summary.json").write_text(json.dumps(S, ensure_ascii=False, indent=1), encoding="utf8")
for n in INST:
    r = runs[n]
    print(n, r["status"], r.get("cost"), r.get("gap_ref"), "dual", round(r["dual_bound"], 2), "nodes", r["nodes"], "t", round(r["solving_time_s"]))
print("O7 t_opt", o7["t_opt"], "| long:", proof)
